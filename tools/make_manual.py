FONT = "微软雅黑"
GRAY = RGBColor(0x60, 0x60, 0x60)
CODE_BG = "F4F5F7"


def set_font(run, size=10.5, bold=False, color=None, mono=False):
    name = "Consolas" if mono else FONT
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color


def add_heading(doc, text, level=1):
    h = doc.add_heading("", level=level)
    run = h.add_run(text)
    set_font(run, {1: 17, 2: 13.5, 3: 11.5}.get(level, 11), bold=True)
    return h


def add_para(doc, text, size=10.5, bold=False, color=None, space=5):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space)
    run = p.add_run(text)
    set_font(run, size, bold, color)
    return p


def add_bullet(doc, text, size=10):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.space_after = Pt(2)
    run = p.add_run(text)
    set_font(run, size)
    return p


def add_code(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.left_indent = Pt(10)
    run = p.add_run(text)
    set_font(run, 9, mono=True)
    return p


def add_table(doc, headers, rows, widths=None, size=9):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        cell = t.rows[0].cells[j]
        cell.text = ""
        run = cell.paragraphs[0].add_run(str(h))
        set_font(run, size, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for j, v in enumerate(row):
            cells[j].text = ""
            run = cells[j].paragraphs[0].add_run(str(v))
            set_font(run, size)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


